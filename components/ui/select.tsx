// ---------------------------------------------------------------------------
// Thin wrapper preserving the simple `options` API used in bookmarks-app.tsx
// so we don't have to rewrite each call site as compositional shadcn JSX.
// ---------------------------------------------------------------------------

export type OptionSelectOption<T extends string = string> = {
  value: T
  label: React.ReactNode
}

type OptionSelectProps<T extends string> = {
  value: T
  onValueChange: (value: T) => void
  options: OptionSelectOption<T>[]
  ariaLabel?: string
  leadingIcon?: React.ReactNode
  className?: string
}

export function OptionSelect<T extends string>({
  value,
  onValueChange,
  options,
  ariaLabel,
  leadingIcon,
  className,
}: OptionSelectProps<T>) {
  return (
    <Select value={value} onValueChange={(v) => onValueChange(v as T)}>
      <SelectTrigger
        aria-label={ariaLabel}
        className={cn(
          "h-10 w-full rounded-md border border-[color:var(--color-hairline)] bg-[color:var(--color-canvas)] pl-3 pr-2 text-sm font-medium text-[color:var(--color-ink)] outline-none transition hover:bg-[color:var(--color-surface-card)] focus-visible:border-[color:var(--color-primary)] focus-visible:ring-[3px] focus-visible:ring-[color:var(--color-primary)]/15 data-[state=open]:border-[color:var(--color-primary)]",
          className
        )}
      >
        <span className="flex min-w-0 flex-1 items-center gap-2">
          {leadingIcon ? (
            <span className="grid h-4 w-4 shrink-0 place-items-center text-[color:var(--color-muted)]">
              {leadingIcon}
            </span>
          ) : null}
          <SelectValue />
        </span>
      </SelectTrigger>
      <SelectContent className="rounded-lg border border-[color:var(--color-hairline)] bg-[color:var(--color-canvas)] py-1 text-sm shadow-[0_8px_24px_rgba(20,20,19,0.10)]">
        {options.map((opt) => (
          <SelectItem
            key={opt.value}
            value={opt.value}
            className="min-h-9 cursor-default rounded-sm pl-8 pr-2.5 text-[color:var(--color-ink)] focus:bg-[color:var(--color-surface-card)] data-[state=checked]:font-semibold data-[state=checked]:text-[color:var(--color-primary)]"
          >
            {opt.label}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  )
}
