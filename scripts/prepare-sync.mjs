// Preflight for `npm run sync`: guarantee the two INCREMENTAL INPUT files exist locally before
// xrelay + the embed step run, restoring them from the private R2 bucket if missing.
//
// Why this exists (learned the hard way, 2026-07):
//  - all-bookmarks.json is xrelay's incremental base. If it's MISSING when `xrelay archive … --limit
//    N` runs, xrelay does a capped FRESH pull and silently drops every bookmark beyond N (the corpus
//    is already > 5000). Restoring it first keeps the pull incremental and lossless.
//  - search-index-bge.json is the embed step's reuse base (fingerprint-diff in embed-bge.mjs). Missing
//    → a full, costly re-embed of the whole corpus. upload-r2.mjs backs it up to R2 (backup-only).
// Both files live ONLY on local disk otherwise (public/data is gitignored since the T8 lockdown), so a
// fresh clone / lost disk / accidental delete would otherwise corrupt or massively bloat a sync.
//
// SAFE BY DEFAULT: if a file is missing and we canNOT positively determine R2's state (auth or network
// error), STOP (exit 1, which halts the `&&` chain in `npm run sync`) — never proceed past a missing
// all-bookmarks.json on ambiguity, because proceeding risks truncating the archive. A CONFIRMED
// "object not found" is treated as a genuine first-ever run and allowed through.
//
// No auth is needed when both files are already present (the common case) — it's a pure no-op then.
import { existsSync, renameSync, rmSync, statSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BUCKET = "bookmark-search-data";

// The two incremental-INPUT files. Everything else (lunr-index, rerank-docs, the packed .bin/.meta)
// is an OUTPUT regenerated by sync-bge from these two, so it never needs restoring.
const INPUTS = ["all-bookmarks.json", "search-index-bge.json"];

// A valid download is far larger than this; guards against an empty/partial/error-body file that
// existsSync would otherwise accept as "present".
const MIN_VALID_BYTES = 1024;

/** The repo-pinned wrangler (worker/package.json), not whatever `npx` would download today. */
function wranglerCmd() {
  const pinned = join(root, "worker", "node_modules", ".bin", "wrangler");
  return existsSync(pinned) ? [pinned, []] : ["npx", ["wrangler"]];
}

function log(m) {
  console.log(`[prepare-sync] ${m}`);
}

function stop(name, wranglerOutput) {
  console.error(
    `[prepare-sync] Could not restore ${name} from R2 and cannot confirm R2's state.\n` +
      `  REFUSING to continue — proceeding with a missing all-bookmarks.json can TRUNCATE your archive.\n` +
      `  Most likely cause: Cloudflare auth is missing. Fix, then re-run \`npm run sync\`:\n` +
      `    • cd worker && npx wrangler login      (browser OAuth)\n` +
      `    • export CLOUDFLARE_API_TOKEN=<token>   (this shell only)\n` +
      (wranglerOutput.trim()
        ? `  wrangler said:\n    ${wranglerOutput.trim().split("\n").slice(-4).join("\n    ")}\n`
        : ""),
  );
  process.exit(1);
}

for (const name of INPUTS) {
  const filePath = join(root, "public/data", name);

  if (existsSync(filePath) && statSync(filePath).size >= MIN_VALID_BYTES) {
    log(`${name} present — ok`);
    continue;
  }

  log(`${name} missing locally — restoring from r2://${BUCKET}/${name} …`);
  // Download to a temp file and rename only a complete, plausible download into place: a killed or
  // failed transfer must never leave a partial file at the real path (it would pass existsSync next run).
  const tmpPath = `${filePath}.download`;
  const [cmd, pre] = wranglerCmd();
  const res = spawnSync(cmd, [...pre, "r2", "object", "get", `${BUCKET}/${name}`, "--file", tmpPath, "--remote"], {
    cwd: root,
    encoding: "utf8",
    env: process.env,
  });
  const out = `${res.stdout || ""}${res.stderr || ""}`;

  if (res.status === 0 && existsSync(tmpPath) && statSync(tmpPath).size >= MIN_VALID_BYTES) {
    renameSync(tmpPath, filePath);
    log(`restored ${name} from R2 (${(statSync(filePath).size / 1e6).toFixed(1)} MB).`);
    continue;
  }

  // Failure: clean up any empty/partial download, then decide.
  try {
    if (existsSync(tmpPath)) rmSync(tmpPath);
  } catch {
    /* ignore */
  }

  // A CONFIRMED "object not found" means R2 genuinely doesn't have it → a first-ever run. Safe to
  // continue: xrelay will create all-bookmarks.json fresh; a missing embed base just means a full
  // (still correct) embed. Any OTHER failure (auth, network, partial) is ambiguous → STOP.
  if (/does not exist|not found|no such key|nosuchkey|the specified key|10007/i.test(out)) {
    log(`${name} is not in R2 either — treating as a first-ever run (it will be built from scratch).`);
    continue;
  }
  stop(name, out);
}

log("inputs ready — proceeding with sync.");
